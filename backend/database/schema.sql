-- AtClam PostgreSQL schema (created automatically by backend/db.py init_db()).
-- Kept here as a reference for pgAdmin / psql users.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS students(
    id TEXT PRIMARY KEY, name CITEXT UNIQUE, embeddings TEXT);

CREATE TABLE IF NOT EXISTS sessions(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT, started_at DOUBLE PRECISION,
    ended_at DOUBLE PRECISION, class_id TEXT);

CREATE TABLE IF NOT EXISTS attendance(
    session_id BIGINT, student_id TEXT, seen_at DOUBLE PRECISION, status TEXT,
    PRIMARY KEY(session_id, student_id));

CREATE TABLE IF NOT EXISTS users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    username CITEXT NOT NULL UNIQUE,
    email CITEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin','instructor','student')),
    student_id TEXT UNIQUE REFERENCES students(id),
    section TEXT DEFAULT '',
    created_at DOUBLE PRECISION NOT NULL,
    school_id TEXT DEFAULT '',
    is_active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS classes(
    id TEXT PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    section TEXT DEFAULT '',
    instructor_id INTEGER,
    present_time TEXT DEFAULT '',
    late_time TEXT DEFAULT '',
    end_time TEXT DEFAULT '',
    created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS enrollments(
    class_id TEXT NOT NULL,
    user_id INTEGER NOT NULL,
    joined_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY(class_id, user_id)
);

CREATE TABLE IF NOT EXISTS announcements(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id TEXT NOT NULL,
    instructor_id INTEGER NOT NULL,
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS excuses(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id TEXT NOT NULL,
    user_id INTEGER NOT NULL,
    date TEXT NOT NULL,
    note TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    UNIQUE(class_id, user_id, date)
);

CREATE TABLE IF NOT EXISTS notifications(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    class_id TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    read_at DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id, id);
CREATE INDEX IF NOT EXISTS idx_sessions_class ON sessions(class_id);
CREATE INDEX IF NOT EXISTS idx_enroll_user ON enrollments(user_id);
CREATE INDEX IF NOT EXISTS idx_ann_class ON announcements(class_id);
