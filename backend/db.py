# --------------------------------------------------------------- SQL bridge
def _translate(sql: str) -> str:
    """Old SQLite SQL -> PostgreSQL SQL."""
    was_ignore = bool(re.search(r"\bINSERT\s+OR\s+IGNORE\b", sql, re.I))
    sql = re.sub(r"\bINSERT\s+OR\s+IGNORE\b", "INSERT", sql, flags=re.I)
    sql = re.sub(r"\s+COLLATE\s+NOCASE\b", "", sql, flags=re.I)
    sql = sql.replace("?", "%s")
    if was_ignore and "ON CONFLICT" not in sql.upper():
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


class Cursor:
    """Thin wrapper that restores sqlite3's ``lastrowid``."""

    def __init__(self, con, raw):
        self._con = con
        self._raw = raw
        self._lastrowid = None

    @property
    def lastrowid(self):
        if self._lastrowid is None:
            row = self._con.execute("SELECT lastval() AS id").fetchone()
            self._lastrowid = row["id"] if row else None
        return self._lastrowid

    @property
    def description(self):
        return self._raw.description

    @property
    def rowcount(self):
        return self._raw.rowcount

    def fetchone(self):
        return self._raw.fetchone()

    def fetchall(self):
        return self._raw.fetchall()

    def fetchmany(self, size=1):
        return self._raw.fetchmany(size)

    def __iter__(self):
        return iter(self._raw)


class Connection:
    """psycopg3 connection with the small subset of sqlite3 API we use."""

    def __init__(self):
        self._con = psycopg.connect(**CONNINFO, row_factory=dict_row)

    def execute(self, sql, params=None):
        return Cursor(self._con, self._con.execute(_translate(sql), params))

    def executemany(self, sql, seq):
        with self._con.cursor() as cur:
            return cur.executemany(_translate(sql), seq)

    def executescript(self, script):
        for stmt in script.split(";"):
            if stmt.strip():
                self._con.execute(stmt)

    def commit(self):
        self._con.commit()

    def rollback(self):
        self._con.rollback()

    def close(self):
        self._con.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type:
            self.rollback()
        else:
            self.commit()
        return False


def get_connection() -> Connection:
    return Connection()


def rows_to_dicts(cur) -> list:
    cols = [c[0] for c in cur.description] if cur.description else []
    return [dict(zip(cols, row)) for row in cur.fetchall()]


def one_to_dict(cur):
    if not cur.description:
        return None
    row = cur.fetchone()
    return dict(zip([c[0] for c in cur.description], row)) if row else None


def init_db() -> None:
    """Create tables and make sure an admin account exists."""
    C.DATA.mkdir(parents=True, exist_ok=True)
    C.FACES.mkdir(parents=True, exist_ok=True)
    C.AVATARS.mkdir(parents=True, exist_ok=True)
    with _write_lock, closing(get_connection()) as con, con:
        con.executescript(SCHEMA)
        if not con.execute("SELECT 1 FROM users WHERE role='admin' LIMIT 1").fetchone():
            from auth import hash_password
            import time
            con.execute(
                """INSERT INTO users(full_name,username,email,password_hash,role,
                                     school_id,section,created_at)
                   VALUES(%s,%s,%s,%s,'admin',%s,%s,%s)""",
                ("AtClam Administrator", "admin", "admin@classroom.local",
                 hash_password("Admin123"), "", "", time.time()),
            )


def user_public(row) -> dict:
    """The user shape shared by every API response / Flutter AppUser model."""
    r = dict(row)
    uid = r["id"]
    student_id = r.get("student_id")
    return {
        "id": uid,
        "name": r.get("full_name", ""),
        "full_name": r.get("full_name", ""),
        "username": r.get("username", ""),
        "email": r.get("email", ""),
        "role": r.get("role", "student"),
        "school_id": r.get("school_id") or "",
        "section": r.get("section") or "",
        "student_id": student_id,
        "has_face": bool(student_id),
        "is_active": bool(r.get("is_active", 1)),
    }


def get_user(uid):
    with closing(get_connection()) as con:
        row = con.execute("SELECT * FROM users WHERE id=%s", (uid,)).fetchone()
    return dict(row) if row else None


def get_class(cid):
    with closing(get_connection()) as con:
        row = con.execute(
            """SELECT c.*, u.full_name AS instructor_name FROM classes c
               LEFT JOIN users u ON u.id=c.instructor_id WHERE c.id=%s""", (cid,)
        ).fetchone()
    return dict(row) if row else None
